const dict: Record<Lang, Partial<Record<Key, string>>> = { en, te };

export function translate(lang: Lang, k: Key, v?: Record<string, string | number>) {
  let s = dict[lang][k] ?? en[k];
  if (v) for (const [a, b] of Object.entries(v)) s = s.split(`{${a}}`).join(String(b));
  return s;
}
