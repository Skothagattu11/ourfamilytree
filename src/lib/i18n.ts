export const tr = (k: Key, v?: Record<string, string | number>) => translate(useData.getState().lang, k, v);

export function useT() {
  const lang = useData(s => s.lang);
  return useCallback((k: Key, v?: Record<string, string | number>) => translate(lang, k, v), [lang]);
}
